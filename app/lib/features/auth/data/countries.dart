/// Country calling codes for the phone login picker.
class Country {
  const Country(this.iso, this.name, this.dialCode, [this.digits]);

  /// ISO 3166-1 alpha-2 code, e.g. "IN".
  final String iso;
  final String name;

  /// With the leading "+", e.g. "+91".
  final String dialCode;

  /// Expected national number length, when it is fixed. Null accepts 4-14 digits.
  final int? digits;

  /// Flag emoji built from the ISO code's regional indicator letters.
  String get flag => String.fromCharCodes(
    iso.toUpperCase().codeUnits.map((c) => c - 0x41 + 0x1F1E6),
  );
}

